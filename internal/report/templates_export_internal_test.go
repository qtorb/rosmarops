// Each exported template file is exactly what «Choose a template» copies
// after its sentence (or, for a launch command, all it copies), on macOS,
// where every template shows; and every template the report offers is
// exported.
func TestExportTemplates_SameAsTheReport(t *testing.T) {
	cat, err := catalog.Load("en")
	if err != nil {
		t.Fatal(err)
	}
	files, err := ExportTemplates("0.16.0")
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]string{}
	for _, f := range files {
		got[f.Path] = f.Content
	}
	c := htmlCtx{v: V2{OS: "darwin"}, cat: cat}
	want := map[string]string{} // path → what the report copies
	for _, id := range c.ccIDs() {
		file := "settings.json"
		if id == profiles.P3 {
			file = "command.txt"
		}
		want["templates/claude-code/"+templateUse[id]+"/"+file] = c.copyText(id)
	}
	for _, g := range c.guided() {
		for _, p := range g.profiles {
			text := c.guidedText(g, p)
			if text == "" {
				continue
			}
			file := map[string]string{profiles.GuidedCursor: "sandbox.json", profiles.GuidedGrok: "config.toml"}[g.key]
			if p.cmd {
				file = "command.txt"
			}
			want["templates/"+g.key+"/"+templateUse[p.id]+"/"+file] = text
		}
	}
	if len(want) == 0 {
		t.Fatal("the report offers no template")
	}
	for path, copied := range want {
		exported, ok := got[path]
		if !ok {
			t.Errorf("%s: the report offers it, the export has no such file", path)
			continue
		}
		block := strings.TrimSuffix(exported, "\n")
		if copied != block && !strings.HasSuffix(copied, "\n\n"+block) {
			t.Errorf("%s: the export is not what the report copies:\nexport %q\nreport %q", path, block, copied)
		}
		if _, ok := got[filepath.ToSlash(filepath.Dir(path))+"/README.md"]; !ok {
			t.Errorf("%s: no README beside it", path)
		}
	}
	for path := range got {
		if strings.HasSuffix(path, "README.md") {
			continue
		}
		if _, ok := want[path]; !ok {
			t.Errorf("%s: exported, but the report does not offer it", path)
		}
	}
}

// The READMEs are catalog texts only, end with the generated line, and leave
// no {param} unfilled.
func TestExportTemplates_Readmes(t *testing.T) {
	files, err := ExportTemplates("0.16.0")
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range files {
		if !strings.HasSuffix(f.Path, "README.md") {
			continue
		}
		if !strings.HasSuffix(f.Content, "\nGenerated by RosmarOps 0.16.0. Do not edit by hand.\n") {
			t.Errorf("%s: no generated line", f.Path)
		}
		if strings.Contains(f.Content, "{") || strings.Contains(f.Content, "[cc.") || strings.Contains(f.Content, "[gp.") {
			t.Errorf("%s: a key or a parameter is left: %q", f.Path, f.Content)
		}
	}
}

// Nothing exported comes from the computer that runs the export: no home,
// user, host, working or temporary folder, and the same bytes on every run.
func TestExportTemplates_NothingFromTheComputer(t *testing.T) {
	a, err := ExportTemplates("0.16.0")
	if err != nil {
		t.Fatal(err)
	}
	b, err := ExportTemplates("0.16.0")
	if err != nil {
		t.Fatal(err)
	}
	if len(a) != len(b) {
		t.Fatal("two exports differ")
	}
	var forbidden []string
	if h, err := os.UserHomeDir(); err == nil && len(h) > 1 {
		forbidden = append(forbidden, h)
	}
	if u, err := user.Current(); err == nil && len(u.Username) > 2 {
		forbidden = append(forbidden, u.Username)
	}
	if h, err := os.Hostname(); err == nil && len(h) > 2 {
		forbidden = append(forbidden, h)
	}
	if wd, err := os.Getwd(); err == nil {
		forbidden = append(forbidden, wd)
	}
	forbidden = append(forbidden, os.TempDir())
	for i, f := range a {
		if f != b[i] {
			t.Errorf("%s: not the same on two runs", f.Path)
		}
		for _, s := range forbidden {
			if strings.Contains(f.Content, s) {
				t.Errorf("%s carries %q from this computer", f.Path, s)
			}
		}
	}
}
